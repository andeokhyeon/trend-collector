def biz():
    g = os.environ.get
    return {
        "name":  g("BIZ_NAME", "AD소프트웨어"),
        "owner": g("BIZ_OWNER", ""),
        "reg":   g("BIZ_REG_NO", ""),
        "mail":  g("BIZ_MAIL_NO", ""),
        "addr":  g("BIZ_ADDR", ""),
        "email": g("BIZ_EMAIL", ""),
        "phone": g("BIZ_PHONE", ""),
    }


def _art(no, title, *paras):
    body = "".join(f"<p>{p}</p>" for p in paras)
    return f'<div class="lg-art"><h3>제{no}조 ({title})</h3>{body}</div>'


